/**
 * YouTubeのチャンネルのURLのパスか（`/@名前`・`/channel/`・`/c/`・`/user/`）。
 * YouTubeのブランド規定は、ロゴ・アイコンをリンクにしてよいのは行き先がチャンネルの
 * 時だけとしているため、動画・再生リスト・`youtu.be`などにはアイコンを出さない
 * （2026-11-18）。アプリ側（`lib/utils/sns_icon.dart`）と同じ規則。
 */
export function isYouTubeChannelPath(path: string): boolean {
  const lower = path.toLowerCase();
  return (
    lower.startsWith("/@") ||
    lower.startsWith("/channel/") ||
    lower.startsWith("/c/") ||
    lower.startsWith("/user/")
  );
}

/** [url]に対応するアイコンの名前。無ければnull。 */
export function snsIconNameFor(url: string): string | null {
  let host: string;
  let path: string;
  try {
    const parsed = new URL(url);
    host = parsed.hostname.toLowerCase();
    path = parsed.pathname;
  } catch {
    return null;
  }
  host = host.replace(/^(www|m|mobile)\./, "");
  if (!host) return null;
  for (const [domain, name] of Object.entries(SNS_ICON_DOMAINS)) {
    if (host === domain || host.endsWith(`.${domain}`)) {
      if (name === "youtube" && !isYouTubeChannelPath(path)) return null;
      return name;
    }
  }
  return null;
}

/** CSSの色（`#rgb`・`#rrggbb`・`rgb()`・`rgba()`）の相対輝度（0〜1）。解釈できなければnull。 */
export function cssColorLuminance(color: string): number | null {
  let r: number, g: number, b: number;
  const hex = /^#([0-9a-f]{3}|[0-9a-f]{6})$/i.exec(color.trim());
  if (hex) {
    const h = hex[1].length === 3 ? hex[1].replace(/./g, (c) => c + c) : hex[1];
    r = parseInt(h.slice(0, 2), 16);
    g = parseInt(h.slice(2, 4), 16);
    b = parseInt(h.slice(4, 6), 16);
  } else {
    const m = /^rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)/i.exec(color.trim());
    if (!m) return null;
    r = Number(m[1]);
    g = Number(m[2]);
    b = Number(m[3]);
  }
  const lin = (v: number) => {
    const c = v / 255;
    return c <= 0.03928 ? c / 12.92 : Math.pow((c + 0.055) / 1.055, 2.4);
  };
  return 0.2126 * lin(r) + 0.7152 * lin(g) + 0.0722 * lin(b);
}

/**
 * 公式のロゴをdata URIにする（Satoriの`<img>`に渡す）。公式素材を同梱していない名前は
 * null。[textColor]（カードの文字色）が明るければ背景は暗いので、暗い背景用（白）の版にする。
 * 色は変えない（各社の規定）。
 */
export function snsIconDataUri(name: string, textColor: string): string | null {
  const svg = SNS_OFFICIAL_ICON_SVGS[name];
  if (!svg) return null;
  const luminance = cssColorLuminance(textColor);
  const onDark = luminance !== null && luminance > 0.5;
  return `data:image/svg+xml;base64,${Buffer.from(onDark ? svg.dark : svg.light).toString("base64")}`;
}
